/**
 * Returns the message dictionary for a language (falls back to English).
 * @param {string} [language]
 */
function t(language) {
  return MESSAGES[language] || MESSAGES.en;
}

/**
 * Renders PR progress text: completed steps get ✅, the current one gets "…".
 * @param {Object} msg - dictionary from t()
 * @param {number} done - number of completed steps
 */
function prProgress(msg, done) {
  const markers = ["①", "②", "③"];
  const lines = msg.prSteps.slice(0, done + 1).map((step, i) => `${markers[i]} ${step} ${i < done ? "✅" : "…"}`);
  return `${msg.prCreating}\n\n${lines.join("\n")}`;
}

module.exports = { ALERTS, MESSAGES, t, prProgress };
